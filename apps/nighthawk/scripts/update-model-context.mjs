#!/usr/bin/env node
/**
 * Generates a model-name → context-length lookup table from the public
 * models.dev model metadata (`models.json`), so OpenAI-compatible /v1/models
 * responses that omit `context_length` still get the right context window
 * (e.g. DeepSeek V4 at 1M tokens instead of the 128k fallback).
 *
 * The table is keyed by the lowercase model id's last path segment (the part
 * after the final `/`), matching how provider aliases are written in
 * config.toml (`provider/model`). Suffixes such as `:free` are stripped.
 * When one model name appears under several providers, the largest declared
 * context wins — the table is a capability upper bound, never a truncation.
 *
 * Usage:
 *   node update-model-context.mjs [--out packages/oauth/src/generated/model-context.ts]
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const args = process.argv.slice(2);
const outFlag = args.indexOf("--out");
const outFile = resolve(
  outFlag >= 0 ? args[outFlag + 1] : "packages/oauth/src/generated/model-context.ts",
);
const modelsUrl = process.env.MODELS_DEV_MODELS_URL || "https://raw.githubusercontent.com/anomalyco/models.dev/dev/models.json";

const res = await fetch(modelsUrl, { headers: { Accept: "application/json" } });
if (!res.ok) throw new Error(`HTTP ${res.status} fetching ${modelsUrl}`);
const payload = await res.json();
const entries = Array.isArray(payload) ? payload : payload.data;
if (!Array.isArray(entries)) throw new Error("unexpected payload shape");

const table = new Map();
for (const entry of entries) {
  const id = typeof entry.id === "string" ? entry.id : "";
  const context = entry.context_length;
  if (!Number.isInteger(context) || context <= 0) continue;
  const segments = id.split("/");
  let model = segments[segments.length - 1] ?? "";
  model = model.split(":")[0].toLowerCase().trim();
  if (model.length === 0) continue;
  const current = table.get(model);
  if (current === undefined || context > current) table.set(model, context);
}

const sorted = [...table.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = sorted.map(([model, context]) => `  '${model}': ${context},`).join("\n");
const ts = `// Generated by scripts/update-model-context.mjs — do not edit by hand.
// Source: ${modelsUrl}
export const MODEL_CONTEXT_LENGTH: Readonly<Record<string, number>> = {
${body}
};

export function lookupModelContextLength(modelId: string): number | undefined {
  const segments = modelId.split('/');
  const model = ((segments[segments.length - 1] ?? '').split(':')[0] ?? '').toLowerCase();
  return MODEL_CONTEXT_LENGTH[model];
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ts, "utf-8");
console.log(`Wrote ${outFile} (${sorted.length} models)`);
